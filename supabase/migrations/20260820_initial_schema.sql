-- RLS helper functions avoid recursive policies on group_members.
create or replace function public.is_group_member(target_group_id integer)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.group_members
    where group_id = target_group_id
      and user_id = auth.uid()
  );
$$;

create or replace function public.is_patient_group_member(target_patient_id integer)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.patients p
    join public.group_members gm on gm.group_id = p.group_id
    where p.id = target_patient_id
      and gm.user_id = auth.uid()
  );
$$;

revoke execute on function public.is_group_member(integer) from public;
revoke execute on function public.is_patient_group_member(integer) from public;
grant execute on function public.is_group_member(integer) to authenticated;
grant execute on function public.is_patient_group_member(integer) to authenticated;

create or replace function public.join_group_by_invite(
  invite_code_input varchar,
  nickname_input varchar,
  relation_input varchar
)
returns public.group_members
language plpgsql
security definer
set search_path = public
as $$
declare
  target_group public.groups;
  membership public.group_members;
begin
  if auth.uid() is null then
    raise exception 'authentication required';
  end if;

  select * into target_group
  from public.groups
  where invite_code = invite_code_input;

  if target_group.id is null then
    raise exception 'invalid invite code';
  end if;

  insert into public.group_members (user_id, group_id, patients_nickname, patient_relation)
  select auth.uid(), target_group.id, nickname_input, relation_input
  on conflict (user_id, group_id) do update
    set patients_nickname = excluded.patients_nickname,
        patient_relation = excluded.patient_relation
  returning * into membership;

  return membership;
end;
$$;

grant execute on function public.join_group_by_invite(varchar, varchar, varchar) to authenticated;

